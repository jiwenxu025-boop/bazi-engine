def analyze_palace_stars(pillars_data: list[dict],
                         spirits: list,
                         day_master: Tiangan) -> PalaceStarResult:
    """宫位叠象分析——将每柱的宫位含义、十神、神煞三者叠合。

    Args:
        pillars_data: 从 build_pillars_data_for_analysis(chart) 获取的四柱数据
        spirits: chart.spirits (list[SpiritAgent])
        day_master: 日主天干

    Returns:
        PalaceStarResult with layered interpretation per pillar
    """
    # 构建 柱位 → 神煞列表 的映射
    pillar_spirits: dict[str, list[str]] = {"年柱": [], "月柱": [], "日柱": [], "时柱": []}
    for sp in spirits:
        pillar = getattr(sp, 'pillar', '')
        name = getattr(sp, 'name', '')
        if pillar in pillar_spirits and name:
            pillar_spirits[pillar].append(name)

    entries: list[PalaceLayerEntry] = []
    for pd in pillars_data:
        pillar_type = pd.get("pillar_type", "")
        ten_god = pd.get("ten_god", "")
        if not ten_god or ten_god == "日主":
            ten_god_display = "日主"
        else:
            ten_god_display = ten_god

        palace_meaning = _PALACE_MEANINGS.get(pillar_type, "")

        # 查找叠象解读
        key = (pillar_type, ten_god_display)
        layered = _PALACE_STAR_INTERPRETATIONS.get(key, "")

        # 日柱特殊处理：天干为日主，地支藏干反映配偶
        if pillar_type == "日柱" and ten_god_display == "日主":
            # 日柱不按天干解读，按地支藏干解读配偶
            hidden = pd.get("hidden_stems", [])
            if hidden:
                h_stems_str = "/".join(
                    f"{hs.get('stem','')}({hs.get('level','')})"
                    for hs in hidden
                )
                layered = f"日支（夫妻宫）藏干：{h_stems_str}。配偶内在性格由此藏干决定，详见藏干解析。"

        if not layered:
            layered = f"{pillar_type}（{palace_meaning}），天干十神：{ten_god_display}。"

        # 纳音维度
        nayin_name = pd.get("nayin", "")
        if nayin_name:
            nayin_info = _PALACE_NAYIN.get(nayin_name, {})
            ptype_short = {"年柱": "年", "月柱": "月", "日柱": "日", "时柱": "时"}.get(pillar_type, "")
            nayin_palace = nayin_info.get(ptype_short, "")
            if nayin_palace:
                layered += f"；纳音层面：{nayin_palace}"

        spirits_here = pillar_spirits.get(pillar_type, [])
        entries.append(PalaceLayerEntry(
            pillar_type=pillar_type,
            palace_meaning=palace_meaning,
            occupying_ten_god=ten_god_display,
            spirits_at_palace=spirits_here,
            layered_interpretation=layered,
        ))

    # 生成总论
    summary_parts = []
    for entry in entries:
        if entry.spirits_at_palace:
            summary_parts.append(
                f"{entry.pillar_type}（{entry.occupying_ten_god}）带神煞"
                f"{','.join(entry.spirits_at_palace)}"
            )

    summary = "；".join(summary_parts) if summary_parts else "四柱宫位叠象无特殊神煞配置。"

    return PalaceStarResult(entries=entries, summary=summary)
