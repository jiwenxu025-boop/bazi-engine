from dataclasses import dataclass, field
from .enums import Tiangan


@dataclass
class PalaceLayerEntry:
    pillar_type: str          # "年柱" | "月柱" | "日柱" | "时柱"
    palace_meaning: str       # 宫位含义
    occupying_ten_god: str    # 占据此宫位的天干十神
    spirits_at_palace: list[str] = field(default_factory=list)
    layered_interpretation: str = ""

    def to_dict(self) -> dict:
        return {
            "pillar_type": self.pillar_type,
            "palace_meaning": self.palace_meaning,
            "occupying_ten_god": self.occupying_ten_god,
            "spirits_at_palace": self.spirits_at_palace,
            "layered_interpretation": self.layered_interpretation,
        }


@dataclass
class PalaceStarResult:
    entries: list[PalaceLayerEntry] = field(default_factory=list)
    summary: str = ""

    def to_dict(self) -> dict:
        return {
            "entries": [e.to_dict() for e in self.entries],
            "summary": self.summary,
        }


